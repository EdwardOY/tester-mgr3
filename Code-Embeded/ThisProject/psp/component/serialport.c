/**
 * @brief	debug com port 硬件中断入口服务函数
 * @param   void
 * @return  void
 * @atten,
 *    -1-, uart_rxbuf must be an array,not a pointer
 *    -2-, pBuff must initially point to DBCOM_ppg.rxbuf, 
           not Uarts_ppg_g[DBCOMs]->rxbuf(because pointer-address cannot be established before)
 ******bkup code**********
		HAL_UART_Receive(&DBCOM_HDR, pBuff++,1, 800);

 */
void DBCOM_IRQHandler(void) //default: USART1_IRQHandler
{	 
	static u8_t* pBuff = DBCOM_ppg.rxbuf; //uart_rxbuf 必须是数组，而不能为指针
  //RX通信时，Instance->DR有数据刷新，UART_FLAG_RXNE就会自动置位
	if(RESET != __HAL_UART_GET_FLAG(DBCOM_ppg.huart,UART_FLAG_RXNE)) 
	{ 
		 *(pBuff++) =  (u8_t)READ_REG(DBCOM_ppg.huart->Instance->DR); //rxvlu;	 

		 DBCOM_ppg.rxbuf_cnt++;		
		 __HAL_UART_CLEAR_FLAG(DBCOM_ppg.huart,UART_FLAG_RXNE);
	}

	//uart端口从繁忙转变到空闲(包含正常和故障)，UART_FLAG_IDLE就会自动置位
	if(RESET != __HAL_UART_GET_FLAG(DBCOM_ppg.huart,UART_FLAG_IDLE))
	{	   
//      printf("UartInt-IDLE responed\r\n"); 		
//		  DBCOM_RxTkn = True;        // 置位Rx接收完成标志
		  DBCOM_ppg.rxtkn = True; // 置位Rx接收完成标志
		  DBCOM_ppg.rxbuf_precnt = DBCOM_ppg.rxbuf_cnt; //记录上次接收数据的数量
		  DBCOM_ppg.rxbuf_cnt = 0;	//rxbuf计数器清零	  
		  pBuff = DBCOM_ppg.rxbuf;       //pBuff指针归位;
		  __HAL_UART_CLEAR_IDLEFLAG(DBCOM_ppg.huart);
	}	
   
   HAL_UART_IRQHandler(DBCOM_ppg.huart); //DBCOM接收中断可不用执行此步，中断型发送必须执行此步。且它调用回调函数
}//end:void DBCOM_IRQHandler(void)


