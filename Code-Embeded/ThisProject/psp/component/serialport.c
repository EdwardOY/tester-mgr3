/**
 * @brief  nonblock dbcom rx datas in poll with interrupt
 * @state  verified and valid
 * @note  
       -1-,Test with XCOM2.7
 * @param  void
 * @retval void
 *******bkcode*********
			  int tmp = strcmp((char*)g_dbcom_rxbuff,"Delate task1");
			  printf("\r\ntmp = %d, <%s>\r\n\r\n",tmp,(char*)g_dbcom_rxbuff);
			  app_dbcom_rst();
 */
void app_dbcom_rxpoll_it(void)
{
   static uint8_t len;
   static uv16_t times = 0;
	 if(g_dbcom_rx_sta & 0x8000) {        /* 接收到了数据? */
	 
				len = g_dbcom_rx_sta & 0x3fff;  /* 得到此次接收到的数据长度 */
				printf("\r\n您发送的消息为:\r\n");

				HAL_UART_Transmit(&g_dbcom_handle, (uint8_t*)g_dbcom_rxbuff, len, 1000);    /*发送接收到的数据*/

				while(__HAL_UART_GET_FLAG(&g_dbcom_handle, UART_FLAG_TC) != SET);           /*等待发送结束*/
				printf("\r\n\r\n"); 			/* 插入换行 */
			
		    app_dbcom_rst();
		 
		}else{   /* 未接收到了数据? */
				times++;

				if (times % 5000 == 0)
				{
						printf("\r\nEdwoy STM32F429IGTB 串口实验\r\n");
						printf("EDWOY@OUTLOOK.COM\r\n\r\n\r\n");
				}

				if (times % 200 == 0) printf("请输入数据,以回车键结束\r\n");

				if (times % 30  == 0) LED0_TOGGLE(); /* 闪烁LED,提示系统正在运行. */

				stkdly_ms(10);
		}	
}

