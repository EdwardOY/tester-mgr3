/***************************************************
 * @brief  (validated) 
 * @param  void
 * @retval void
 ***************************************************/
uint8_t task_esp_rxmsg_poll(void)
{	
	static emWIFI_DevState_t ret = WIFI_Disconnect;
  static uint8_t *buf = g_atkmodule_rxbuff;
  static sttWIFI_DevParas_t* tmpdev = &g_atkmoudle_esp_dev0;	

  app_handle_espdevsta_poll(buf, tmpdev); // get ESP dev sta_dev
  if(True == g_atkmodule_rxtkn_ovr)
	{
		switch(tmpdev->sta_dev)
		{
			case WIFI_Connect:
				buf = g_atkmodule_rxbuff;
				printf("TTconn-RxMsg:{%s}\r\n",buf);  
				break;
			
			case WIFI_Ready:
			case WIFI_Disconnect:

			  buf = app_atkmodule_get_uartrx_frame();
				printf("Disconn-RxMsg:{%s}\r\n",buf);  
				break;			
			
			default : break;
		}			
		
		app_atkmodule_uartrx_rst(); 
  }
	return ret;
}

/*******************************************************************
 * @brief (validated) tx message handle-poll
           1 WIFI_Connect:	TTconnection,tx msg from dbcom	
			     2 WIFI_Ready or WIFI_Disconnect: AT cmds from dbcom
 * @param  void
 * @notice 
        -1-, dbcom rx dose not save "\r\n",usr must add it
 * @retval 
 ***************************************
 printf("ATcmd:%s; dbcom-rxlen = %d\r\n",cmd,g_dbcom_rx_curcnt);
 *******************************************************************/
uint8_t task_esp_txmsg_poll(void)
{	
	static emWIFI_DevState_t ret = WIFI_Disconnect;
  static uint8_t *buf = g_atkmodule_rxbuff;
  static sttWIFI_DevParas_t* tmpdev = &g_atkmoudle_esp_dev0;	

  app_handle_espdevsta_poll(buf, tmpdev);

  if(True == g_dbcom_rxtkn_ovr)
	{
		switch(tmpdev->sta_dev)
		{
			case WIFI_Connect:	 // TTconnection,tx msg from dbcom	
				app_atkmodule_printf((char*)g_dbcom_rxbuff);
				break;			
				
			case WIFI_Ready:
			case WIFI_Disconnect: //AT cmds from dbcom
				if(NULL == strncmp((sc8_t*)g_dbcom_rxbuff,"AT+",3)) 
				{
					char cmd[12] = {0};
					sprintf(cmd,"%s\r\n",(char*)g_dbcom_rxbuff);
				  printf("ATcmd:%s; dbcom-rxlen = %d\r\n",cmd,g_dbcom_rx_curcnt);
			    app_atkmodule_printf((char*)cmd);
					app_dbcom_rst(); 
          stkdly_ms(__DlyMs_Esp);
				}
        break;
			
			default : break;
		}			
	
    app_dbcom_rst(); 
  }//< if(True == g_dbcom_rxtkn_ovr)>
	
	return ret;
}


