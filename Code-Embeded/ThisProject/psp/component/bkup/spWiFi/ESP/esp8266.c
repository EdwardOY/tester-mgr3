/**
 * @brief       ATK-MW8266D硬件初始化
 * @param       无
 * @retval      无
 */
static void app_esp_rstgpio_init(void)
{
    GPIO_InitTypeDef gpio_init_struct;
    
    WIFI_RST_GPIO_CLK_ENABLE();
    
    gpio_init_struct.Pin   = WIFI_RST_GPIO_PIN;
    gpio_init_struct.Mode  = GPIO_MODE_OUTPUT_PP;
    gpio_init_struct.Pull  = GPIO_NOPULL;
    gpio_init_struct.Speed = GPIO_SPEED_FREQ_HIGH;
    HAL_GPIO_Init(WIFI_RST_GPIO_PORT, &gpio_init_struct);
}

/**
 * @brief       ATK-MW8266D硬件复位
 * @param       无
 * @retval      无
 */
void app_esp_dev_hdrst(void)
{
    WIFI_RST_GPIO(0);
    stkdly_ms(100);
    WIFI_RST_GPIO(1);
    stkdly_ms(500);
}

/**
 * @brief       ATK-MW8266D发送AT指令
 * @param       cmd    : 待发送的AT指令
 *              ack    : 等待的响应
 *              timeout: 等待超时时间
 * @retval      Err_WIFI_NONE     : 函数执行成功
 *              Err_WIFI_TIMEOUT: 等待期望应答超时，函数执行失败
 */
uint8_t app_esp_send_at_cmd(char *cmd, char *ack, uint32_t timeout)
{
    uint8_t *ret = NULL;
    
//    app_atkmodule_uartrx_restart();
	  app_atkmodule_uartrx_rst();
    app_atkmodule_printf("%s\r\n", cmd);
    
    if ((ack == NULL) || (timeout == 0)){
        return Err_WIFI_NONE;
			
    }else{
        while (timeout > 0)
        {
            ret = app_atkmodule_get_uartrx_frame();
            if (ret != NULL)
            {
                if (strstr((const char *)ret, ack) != NULL)
                {
                    return Err_WIFI_NONE;
                }
                else
                {
                    app_atkmodule_uartrx_rst(); //app_atkmodule_uartrx_restart();
                }
            }
            timeout--;
            stkdly_ms(1);
        }
        
        return Err_WIFI_TIMEOUT;
    }
}

